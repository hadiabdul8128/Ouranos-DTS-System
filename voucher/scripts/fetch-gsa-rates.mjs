// Refresh the bundled CONUS per-diem tables from the official GSA Per Diem API.
// Usage: GSA_API_KEY=... node scripts/fetch-gsa-rates.mjs 2026 2027
// DEMO_KEY works for a manual refresh but is heavily rate-limited.
import { writeFile } from 'node:fs/promises';

const key = process.env.GSA_API_KEY || 'DEMO_KEY';
const years = process.argv.slice(2).map(Number).filter(Number.isInteger);
if (!years.length) throw new Error('Pass one or more fiscal years, e.g. 2026 2027.');
const months = ['Oct', 'Nov', 'Dec', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep'];

async function get(path) {
  const response = await fetch(`https://api.gsa.gov/travel/perdiem/v2/${path}`, { headers: { 'x-api-key': key } });
  if (!response.ok) throw new Error(`GSA ${path} returned ${response.status}`);
  return response.json();
}

for (const year of years) {
  const [lodging, mie] = await Promise.all([get(`rates/conus/lodging/${year}`), get(`rates/conus/mie/${year}`)]);
  if (!Array.isArray(lodging) || lodging.length < 100) throw new Error(`FY${year} lodging table looks incomplete.`);
  const table = {
    fiscalYear: year,
    source: `GSA Per Diem API · CONUS FY${year}`,
    fetchedAt: new Date().toISOString().slice(0, 10),
    // Fiscal-year column order: Oct, Nov, Dec of the prior calendar year, then Jan–Sep.
    monthOrder: months,
    mie: mie.map(row => ({ total: row.total, breakfast: row.breakfast, lunch: row.lunch, dinner: row.dinner, incidental: row.incidental, firstLastDay: row.FirstLastDay })),
    locations: lodging.map(row => ({
      city: row.City.trim(), state: row.State, county: (row.County || '').replace(/\s+/g, ' ').trim(),
      meals: Number(row.Meals), lodging: months.map(month => Number(row[month]))
    }))
  };
  const file = new URL(`../src/rates/conus-fy${year}.js`, import.meta.url);
  await writeFile(file, `// Generated by scripts/fetch-gsa-rates.mjs — do not edit by hand.\nexport default ${JSON.stringify(table)};\n`);
  console.log(`Wrote FY${year}: ${table.locations.length} locations, ${table.mie.length} M&IE tiers.`);
}
